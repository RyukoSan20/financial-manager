/**
 * Batch 1 of the words that were still hardcoded in the screens.
 *
 * The main locale files in this folder are owned by someone else, so
 * the words for these screens live here instead. The shape is one
 * plain object per language, and the key names are the same in every
 * language, so a lookup can never fall through to a raw key.
 *
 * A screen picks its language once, at the top of the component, and
 * reads the words straight out of the object:
 *
 *   const { language } = useTranslation();
 *   const K = batch1[language] || batch1.id;
 *
 * There is no t() call here on purpose. A word that is read at the top
 * of a module would throw, and a page that throws is a blank page.
 */

/**
 * Put a value into a word that has a hole in it.
 *
 * The holes are written as {count}, {name} and so on, so the sentence
 * can be put together in the language of the reader rather than in
 * English with the pieces moved around.
 */
export const fill = (text, values = {}) =>
  String(text || '').replace(/\{(\w+)\}/g, (match, key) =>
    values[key] === undefined || values[key] === null ? match : String(values[key])
  );

