/**
 * The words for the shopping grid, the till of a shop, and the tax.
 *
 * Three features that have never had words of their own:
 *
 * - the grid of things to look at, where the price has to say where
 *   it came from;
 * - the till of a shop, where a sale is a basket of things and the
 *   tax has to be worked out;
 * - the invitation to a shared bill, which is a link the host clicks
 *   and sends.
 *
 * The price is the delicate one. A price that came from the reader's
 * own catalogue is not a price in a shop, and the screen says which
 * one it is showing rather than letting the reader guess.
 *
 * Every string is in all three languages, so that the checks in
 * `scripts/` can hold it to that.
 */

/**
 * A %s in a word is a hole. Use fill() to put a value in it.
 *
 * The same helper the other batches use, so that a sentence with a
 * number in it is written the same way everywhere in this
 * application.
 */
export const fill = (template, ...values) => {
  let cursor = 0;
  return String(template ?? '').replace(/%s/g, () =>
    cursor < values.length ? String(values[cursor++]) : '',
  );
};

