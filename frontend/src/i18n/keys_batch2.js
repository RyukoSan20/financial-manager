/**
 * Batch 2 of the UI strings.
 *
 * The main locale files (id.js, en.js, ja.js) hold the keys that the
 * whole app shares. This file holds the strings of a second sweep:
 * the ones that live inside a single screen or a single component.
 *
 * Every language has the same key names. The values are plain strings,
 * so a component can read them with a plain lookup:
 *
 *   const { language } = useTranslation();
 *   const K = batch2[language]?.voice;
 *   ...
 *   {K.title}
 *
 * There is deliberately no t() call here and none at module level in
 * the components that use this file. A module level t() would throw
 * "ReferenceError: t is not defined" and leave the page blank.
 *
 * A %s in a string is a hole. Use fill() to put a value in it:
 *
 *   fill(K.sale_desc, storeName)
 */

export const fill = (template, ...values) => {
  let cursor = 0;
  return String(template ?? '').replace(/%s/g, () =>
    cursor < values.length ? String(values[cursor++]) : '',
  );
};

