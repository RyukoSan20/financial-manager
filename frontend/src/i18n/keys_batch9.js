/**
 * The words for a shared bill.
 *
 * A bill shared between people at a table is a bill in more than one
 * language, and often in more than one script. The terms used here
 * are the ones people actually use:
 *
 * - Indonesian: "talangan" for the money somebody lays out for
 *   others, "bagi rata" for the equal split, and "PB1" for the tax
 *   a restaurant adds.
 * - English: "paid by", "tax / VAT", "equal split", "claim your
 *   items".
 * - Japanese: "割り勘" (warikan) for the split itself, "立替"
 *   (tatekae) for the money laid out for others, and "端数処理"
 *   for the rounding of the leftover.
 *
 * Every string the split bill shows is in here, in all three
 * languages, so that the checks in `scripts/` can hold it to that.
 */

/**
 * A %s in a word is a hole. Use fill() to put a value in it.
 *
 * The same helper the other batches use, so that a sentence with a
 * number in it is written the same way everywhere in this
 * application.
 */
export const fill = (template, ...values) => {
  let cursor = 0;
  return String(template ?? '').replace(/%s/g, () =>
    cursor < values.length ? String(values[cursor++]) : '',
  );
};

